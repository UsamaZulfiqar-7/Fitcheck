"""Write the SQL schema files in db/ from the SQLAlchemy models (single source of truth).

    python scripts/export_schema.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sqlalchemy.dialects import postgresql, sqlite  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from core.db import Base  # noqa: E402

HEADER = "-- FitCheck schema ({name}). Generated by scripts/export_schema.py from core/db.py. Do not edit by hand.\n\n"


def render(dialect, name: str) -> str:
    out = [HEADER.format(name=name)]
    for table in Base.metadata.sorted_tables:
        out.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            out.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";\n")
        out.append("")
    return "\n".join(out)


def main() -> None:
    (ROOT / "db").mkdir(exist_ok=True)
    (ROOT / "db" / "schema_postgres.sql").write_text(render(postgresql.dialect(), "PostgreSQL"), encoding="utf-8")
    (ROOT / "db" / "schema_sqlite.sql").write_text(render(sqlite.dialect(), "SQLite"), encoding="utf-8")
    print("Wrote db/schema_postgres.sql and db/schema_sqlite.sql")


if __name__ == "__main__":
    main()
